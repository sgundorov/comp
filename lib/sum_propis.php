<?php
/**
 * Сумма прописью на русском языке.
 * Пример: 12345.67 → "Двенадцать тысяч триста сорок пять рублей 67 копеек"
 */
function sum_propis(float $sum): string {
    $sum = round($sum, 2);
    $rub = (int)$sum;
    $kop = (int)round(($sum - $rub) * 100);

    $result = number_to_words_ru($rub) . ' ' . plural($rub, 'рубль', 'рубля', 'рублей');
    $result .= ' ' . str_pad($kop, 2, '0', STR_PAD_LEFT) . ' '
             . plural($kop, 'копейка', 'копейки', 'копеек');
    return $result;
}

function plural(int $n, string $one, string $two, string $five): string {
    $n = abs($n) % 100;
    $lastDigit = $n % 10;
    if ($n > 10 && $n < 20) return $five;
    if ($lastDigit > 1 && $lastDigit < 5) return $two;
    if ($lastDigit === 1) return $one;
    return $five;
}

function number_to_words_ru(int $num): string {
    if ($num === 0) return 'Ноль';

    $groups = [
        1 => ['女性' => ['','одна','две','три','четыре','пять','шесть','семь','восемь','девять',
                         'десять','одиннадцать','двенадцать','тринадцать','четырнадцать',
                         'пятнадцать','шестнадцать','семнадцать','восемнадцать','девятнадцать'],
              'муж'  => ['','один','два','три','четыре','пять','шесть','семь','восемь','девять',
                         'десять','одиннадцать','двенадцать','тринадцать','четырнадцать',
                         'пятнадцать','шестнадцать','семнадцать','восемнадцать','девятнадцать'],
        ],
    ];

    $ones = ['','один','два','три','четыре','пять','шесть','семь','восемь','девять'];
    $onesF = ['','одна','две','три','четыре','пять','шесть','семь','восемь','девять'];
    $teens = ['десять','одиннадцать','двенадцать','тринадцать','четырнадцать',
              'пятнадцать','шестнадцать','семнадцать','восемнадцать','девятнадцать'];
    $tens = ['','десять','двадцать','тридцать','сорок','пятьдесят','шестьдесят','семьдесят','восемьдесят','девяносто'];
    $hundreds = ['','сто','двести','триста','четыреста','пятьсот','шестьсот','семьсот','восемьсот','девятьсот'];

    $parts = [];
    if ($num >= 1000000000) {
        $billions = intdiv($num, 1000000000);
        $parts[] = number_to_words_ru($billions) . ' ' . plural($billions, 'миллиард', 'миллиарда', 'миллиардов');
        $num %= 1000000000;
    }
    if ($num >= 1000000) {
        $millions = intdiv($num, 1000000);
        $parts[] = number_to_words_ru($millions) . ' ' . plural($millions, 'миллион', 'миллиона', 'миллионов');
        $num %= 1000000;
    }
    if ($num >= 1000) {
        $thousands = intdiv($num, 1000);
        $parts[] = convert_three_digits($thousands, $onesF) . ' ' . plural($thousands, 'тысяча', 'тысячи', 'тысяч');
        $num %= 1000;
    }
    if ($num > 0) {
        $parts[] = convert_three_digits($num, $ones);
    }

    return implode(' ', $parts);
}

function convert_three_digits(int $n, array $ones): string {
    $teens = ['десять','одиннадцать','двенадцать','тринадцать','четырнадцать',
              'пятнадцать','шестнадцать','семнадцать','восемнадцать','девятнадцать'];
    $tens = ['','десять','двадцать','тридцать','сорок','пятьдесят','шестьдесят','семьдесят','восемьдесят','девяносто'];
    $hundreds = ['','сто','двести','триста','четыреста','пятьсот','шестьсот','семьсот','восемьсот','девятьсот'];

    $result = '';
    $h = intdiv($n, 100);
    if ($h > 0) $result .= $hundreds[$h] . ' ';
    $rest = $n % 100;
    if ($rest >= 10 && $rest < 20) {
        $result .= $teens[$rest - 10];
    } else {
        $t = intdiv($rest, 10);
        if ($t > 0) $result .= $tens[$t] . ' ';
        $o = $rest % 10;
        if ($o > 0) $result .= $ones[$o];
    }
    return trim($result);
}
